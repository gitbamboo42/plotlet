"""Regenerate the shipped JSON Schema for journal-lite blobs.

    python tests/gen_json_schema.py

Writes `src/plotlet/schemas/journal_lite.schema.json`, derived
entirely from `pt.op_schema()` — the registry and the replay
validators — so the schema cannot drift from what a render accepts.
For every op whose parameter list is closed, the entry's `kwargs`
property names are enumerated (typo'd kwargs fail validation before a
render); ops the schema doesn't know (extension artists not imported
here) pass the envelope checks and fail at render instead, with the
better message. Values are deliberately unconstrained: the schema
catches structure and kwarg-name mistakes cheaply, the render
validates everything else. `tests/test_json_schema.py` fails if the
checked-in schema goes stale; rerun this script to fix it.
"""
from __future__ import annotations

from pathlib import Path

import plotlet as pt
from plotlet._json_layer import pretty_dumps

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "plotlet" / "schemas" / "journal_lite.schema.json"


def _kwarg_pool(schema: dict) -> list[str] | None:
    """Union of accepted kwarg names across an op's sections, or None
    when any section is open (**kwargs / params_open)."""
    pool: set[str] = set()
    for section in schema["sections"]:
        if section.get("params_open"):
            return None
        for p in section["params"]:
            name = p["name"]
            if name.startswith("**"):
                return None
            if name.startswith("*"):
                continue        # positional catch-all rides in "args"
            pool.add(name)
        pool.update(section.get("extra_kwargs", ()))
    return sorted(pool)


def _shipped(schema: dict) -> bool:
    """Only ops the wheel ships belong in the shipped schema — an
    extension or user artist registered in this process (tests and the
    site build do this) must not leak in, or regeneration would depend
    on import order."""
    return all(section.get("origin", "core") == "core"
               for section in schema["sections"])


def build_schema() -> dict:
    dump = pt.op_schema()
    per_op = []
    for op in sorted(dump["ops"]):
        if not _shipped(dump["ops"][op]):
            continue
        pool = _kwarg_pool(dump["ops"][op])
        if pool is None:
            continue
        per_op.append({
            "if": {"properties": {"op": {"const": op}}, "required": ["op"]},
            "then": {"properties": {
                "kwargs": {"propertyNames": {"enum": pool}}}},
        })
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": ("https://raw.githubusercontent.com/gitbamboo42/plotlet/"
                "main/src/plotlet/schemas/journal_lite.schema.json"),
        "title": "plotlet journal-lite",
        "description": (
            "The journal-lite authoring form (skills/json.md). Canonical "
            "journals from pt.to_json validate too — lite is a superset "
            "acceptance. Generated by tests/gen_json_schema.py from "
            "pt.op_schema(); never edited by hand."),
        "type": "object",
        "required": ["entries"],
        "properties": {
            "version": {"const": 1},
            "root_nid": {"type": ["integer", "null"]},
            "entries": {"type": "array",
                        "items": {"$ref": "#/$defs/entry"}},
            "data": {"type": "object"},
        },
        "$defs": {
            "entry": {
                "type": "object",
                "required": ["op", "nid"],
                "properties": {
                    "op": {"type": "string"},
                    "nid": {"type": "integer"},
                    "args": {"type": "array"},
                    "kwargs": {"type": "object"},
                },
                "allOf": per_op,
            },
        },
    }


def schema_text() -> str:
    # The same canonical formatter as pt.to_json and the twins — one
    # JSON text convention across everything the wheel ships.
    return pretty_dumps(build_schema()) + "\n"


def main() -> None:
    OUT.parent.mkdir(exist_ok=True)
    text = schema_text()
    # newline="\n" so a Windows regeneration doesn't rewrite the file
    # with CRLF endings (same rule as the twins).
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{OUT.relative_to(HERE.parent)}  ({len(text):,} bytes)")


if __name__ == "__main__":
    main()
